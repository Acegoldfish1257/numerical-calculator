"""Run from the project root to regenerate docs/test_results.md and .csv."""

import csv
from pathlib import Path
import sys
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from examples.verification_cases import cases, evaluate_case


def display(value):
    a = np.asarray(value)
    return (
        f"{float(a):.12g}"
        if a.ndim == 0
        else "[" + ", ".join(f"{float(v):.12g}" for v in a.ravel()) + "]"
    )


def main():
    rows = []
    for case in cases():
        actual, error, passed = evaluate_case(case)
        rows.append(
            [
                case.method,
                case.problem,
                display(case.expected),
                display(actual),
                f"{error:.6g}",
                f"{case.tolerance:.6g}",
                "PASS" if passed else "FAIL",
            ]
        )
    folder = ROOT / "docs"
    folder.mkdir(exist_ok=True)
    headings = [
        "Method",
        "Test problem",
        "Expected",
        "Actual",
        "Maximum absolute error",
        "Tolerance",
        "Status",
    ]
    with (folder / "test_results.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(headings)
        writer.writerows(rows)
    lines = [
        "# Reproducible verification results",
        "",
        "Generated by `python scripts/generate_verification_table.py` from actual computations.",
        "Tolerances are absolute and specific to the stated parameters. Vector comparisons use the largest component error.",
        "Reconstruction/orthogonality rows explicitly compare a computed residual with zero; they do not claim exact factor entries.",
        "These demonstration cases supplement the method, failure-case, parser and Streamlit tests in `tests/`.",
        "",
        "| " + " | ".join(headings) + " |",
        "| " + " | ".join(["---"] * len(headings)) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    (folder / "test_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    passed = sum(row[-1] == "PASS" for row in rows)
    print(f"Verification cases: {passed}/{len(rows)} passed")
    return 0 if passed == len(rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
